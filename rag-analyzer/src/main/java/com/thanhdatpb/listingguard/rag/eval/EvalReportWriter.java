package com.thanhdatpb.listingguard.rag.eval;

import com.thanhdatpb.listingguard.rag.eval.RetrievalEvaluator.Evaluation;
import com.thanhdatpb.listingguard.rag.eval.RetrievalEvaluator.GroupMetrics;
import com.thanhdatpb.listingguard.rag.eval.RetrievalEvaluator.QueryResult;
import com.thanhdatpb.listingguard.rag.retrieval.PolicyRetriever.RetrievedChunk;
import java.time.Instant;
import java.util.List;
import java.util.Locale;

/** Renders an {@link Evaluation} as the Markdown of {@code eval/retrieval/results.md}. Every number comes from the run. */
public final class EvalReportWriter {

    /** @param sourceHash SHA-256 of the saved file, so a result can be tied to the exact corpus it was measured on */
    public record CorpusRow(String file, String title, String version, String sourceHash, int chunks) {
    }

    public record RunInfo(Instant at, String embeddingModel, List<CorpusRow> corpus) {
    }

    private EvalReportWriter() {
    }

    public static String render(Evaluation evaluation, RunInfo run) {
        StringBuilder md = new StringBuilder();
        md.append("# Retrieval evaluation results\n\n");
        md.append("Generated by `eval-retrieval` from `queries.yaml`; do not edit by hand.\n\n");
        md.append("- Run at: ").append(run.at()).append(" (UTC)\n");
        md.append("- Marketplace: ").append(evaluation.marketplace()).append('\n');
        md.append("- Embedding model: `").append(run.embeddingModel()).append("`\n");
        md.append("- Each question is retrieved with k=").append(RetrievalEvaluator.RETRIEVE_K)
                .append("; recall is measured at ").append(RetrievalEvaluator.RECALL_K)
                .append(", MRR over the top ").append(RetrievalEvaluator.RETRIEVE_K).append('\n');
        md.append("- A result is relevant when it comes from the expected document and its heading path starts with the expected "
                + "section (an empty section means only the text before the first heading)\n");
        md.append("- A query counts as a hit at 5 when the top 5 results contain at least one of its labels\n\n");

        md.append("## Summary\n\n");
        md.append("| Language | Queries | Hits in top ").append(RetrievalEvaluator.RECALL_K).append(" | Recall@")
                .append(RetrievalEvaluator.RECALL_K).append(" | MRR@").append(RetrievalEvaluator.RETRIEVE_K).append(" |\n");
        md.append("|---|---|---|---|---|\n");
        for (GroupMetrics group : evaluation.groups()) {
            md.append(String.format(Locale.ROOT, "| %s | %d | %d | %.3f | %.3f |%n", group.language(), group.queries(),
                    group.hitsAtK(), group.recallAtK(), group.mrr()));
        }

        md.append("\n## Corpus\n\n| File | Version | Chunks | source_hash |\n|---|---|---|---|\n");
        for (CorpusRow row : run.corpus()) {
            md.append(String.format(Locale.ROOT, "| %s (%s) | %s | %d | `%s` |%n", row.file(), row.title(), row.version(),
                    row.chunks(), row.sourceHash().substring(0, Math.min(12, row.sourceHash().length()))));
        }

        md.append("\n## Per query\n\n| Query | Language | First relevant rank | Top result |\n|---|---|---|---|\n");
        for (QueryResult result : evaluation.results()) {
            md.append(String.format(Locale.ROOT, "| %s | %s | %s | %s |%n", result.queryId(), result.language(),
                    result.firstHitRank().isPresent() ? String.valueOf(result.firstHitRank().getAsInt()) : "none",
                    result.top().isEmpty() ? "-" : cell(describe(result.top().get(0)))));
        }

        List<QueryResult> misses = evaluation.results().stream()
                .filter(r -> r.firstHitRank().isEmpty() || r.firstHitRank().getAsInt() > RetrievalEvaluator.RECALL_K).toList();
        md.append("\n## Misses (no relevant result in the top ").append(RetrievalEvaluator.RECALL_K).append(")\n\n");
        if (misses.isEmpty()) {
            md.append("None.\n");
        }
        for (QueryResult miss : misses) {
            md.append("### ").append(miss.queryId()).append(" (").append(miss.language()).append(")\n\n");
            md.append("Question: ").append(miss.question()).append("\n\nExpected:\n");
            for (EvalSet.Expected expected : miss.query().expected()) {
                md.append("- ").append(expected.file()).append(" > ")
                        .append(expected.section().isEmpty() ? "(text before the first heading)" : expected.section()).append('\n');
            }
            md.append("\nTop results returned:\n");
            for (RetrievedChunk chunk : miss.top()) {
                md.append("- ").append(describe(chunk)).append('\n');
            }
            md.append('\n');
        }
        return md.toString();
    }

    private static String describe(RetrievedChunk chunk) {
        return String.format(Locale.ROOT, "%s (%.3f)", chunk.sectionPath(), chunk.score());
    }

    private static String cell(String text) {
        return text.replace("|", "\\|");
    }
}
